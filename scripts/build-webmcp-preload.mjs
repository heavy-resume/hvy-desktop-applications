import fs from 'node:fs';

const outputPath = new URL('../src-electron/integration-preload.cjs', import.meta.url);
// Galaxy's channel, given only to the isolated world its scripts run in (integration-inspector.js `__hvyGalaxyHost`).
const host = `// What the main process tells an integration browser's page (main.cjs): the isolated world
// Galaxy's scripts run in, which alone is given Galaxy's channel, out of the page's reach.
const setup = ipcRenderer.sendSync('hvy:integration-page-setup');
contextBridge.exposeInIsolatedWorld(setup.worldId, '__hvyGalaxyHost', {
  publish: (value) => ipcRenderer.send('hvy:integration-page-message', { kind: 'publish', value }),
  toolbarState: (value) => ipcRenderer.send('hvy:integration-page-message', { kind: 'toolbar-state', value }),
  cancel: () => ipcRenderer.send('hvy:integration-page-message', { kind: 'cancel' }),
});`;
const output = `'use strict';\n// Generated by scripts/build-webmcp-preload.mjs.\nconst { contextBridge, ipcRenderer } = require('electron');\n${host}\n`;

fs.writeFileSync(outputPath, output);
